HOEHE = 5


def prepare(text: str) -> str:
    """Text so umformen, wie ihn diese Schrift darstellen kann."""
    return (str(text).upper()
            .replace("Ä", "AE").replace("Ö", "OE").replace("Ü", "UE").replace("ß", "SS"))


def zeilen(text: str) -> list[str]:
    """Text in 5 Bitmuster-Zeilen umsetzen (je Glyph eine Leerspalte Abstand)."""
    rows = [""] * HOEHE
    for ch in text:
        pat = GLYPHEN.get(ch, GLYPHEN[" "])
        for i in range(HOEHE):
            rows[i] += pat[i] + "0"
    return rows


def breite(text: str) -> int:
    return len(zeilen(text)[0]) if text else 0
